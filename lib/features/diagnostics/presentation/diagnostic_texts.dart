  static String get(String? locale, String key, [Map<String, Object>? args]) {
    var text = _texts[locale == 'ru' ? 'ru' : 'uz']?[key] ??
        _texts['uz']?[key] ??
        key;
    args?.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
    return text;
  }

  /// Sarflangan vaqt: "12 daqiqa" / "45 soniya"; saqlanmagan bo'lsa null.
  static String? duration(String? locale, int? seconds) {
    if (seconds == null) return null;
    if (seconds < 60) return get(locale, 'seconds', {'count': seconds});
    return get(locale, 'minutes', {'count': (seconds / 60).round()});
  }
