/// Liga sahifalari matnlari — saytdagi (LigaHome.jsx, LigaTestRun.jsx) bilan bir xil.
String lt(String locale, String key) => (_t[locale == 'ru' ? 'ru' : 'uz']![key]) ?? _t['uz']![key] ?? key;

/// {n} va {m} o'rniga qiymat qo'yadi
String ltf(String locale, String key, Object n, [Object? m]) {
  var text = lt(locale, key).replaceAll('{n}', '$n');
  if (m != null) text = text.replaceAll('{m}', '$m');
  return text;
}

